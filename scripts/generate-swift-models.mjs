// Generated transport structs are separate from future SwiftData entities.
import { readFile, writeFile, mkdir } from 'node:fs/promises'
const contract = JSON.parse(await readFile('contracts/v2/app-data.schema.json', 'utf8'))
const structs = new Map()
const cap = (text) => text[0].toUpperCase() + text.slice(1)
function swiftType(shape, name) {
  if (shape.$ref) return shape.$ref.split('/').at(-1)
  if (shape.anyOf) {
    const variants = shape.anyOf.filter((s) => s.type !== 'null')
    const types = [...new Set(variants.map((s) => swiftType(s, name)))]
    if (types.length !== 1) throw new Error(`Unmapped union: ${name}`)
    return types[0] + (variants.length !== shape.anyOf.length ? '?' : '')
  }
  if ('const' in shape)
    return typeof shape.const === 'string' ? 'String' : typeof shape.const === 'boolean' ? 'Bool' : 'Int'
  if (shape.type === 'string') return 'String'
  if (shape.type === 'number') return 'Decimal'
  if (shape.type === 'boolean') return 'Bool'
  if (shape.type === 'array') return `[${swiftType(shape.items, name + 'Item')}]`
  if (shape.type === 'object') {
    addStruct(name, shape)
    return name
  }
  throw new Error(`Unmapped shape: ${name}`)
}
function addStruct(name, shape) {
  if (structs.has(name)) return
  structs.set(name, '')
  const fields = Object.entries(shape.properties).map(([key, value]) => {
    const optional = !shape.required.includes(key)
    const type = swiftType(value, name + cap(key))
    return { key, type: type + (optional && !type.endsWith('?') ? '?' : ''), optional }
  })
  // Required nullable fields (notably activeGroceryList and ingredient quantity) must encode explicit null.
  structs.set(
    name,
    `public struct ${name}: Codable, Equatable {\n${fields.map((f) => `    public var ${f.key}: ${f.type}`).join('\n')}\n\n    enum CodingKeys: String, CodingKey {\n${fields.map((f) => `        case ${f.key}`).join('\n')}\n    }\n    public func encode(to encoder: Encoder) throws {\n        var container = encoder.container(keyedBy: CodingKeys.self)\n${fields.map((f) => `        try container.${f.optional ? 'encodeIfPresent' : 'encode'}(${f.key}, forKey: .${f.key})`).join('\n')}\n    }\n}`,
  )
}
for (const [name, shape] of Object.entries(contract.$defs)) addStruct(name, shape)
const root = 'native/MyHubCore'
const files = {
  [`${root}/Sources/MyHubCore/Models.swift`]:
    '// Generated by npm run contract:generate. Do not edit.\nimport Foundation\n\n' +
    [...structs.values()].join('\n\n') +
    '\n',
  [`${root}/Sources/MyHubCore/Resources/app-data.schema.json`]: await readFile(
    'contracts/v2/app-data.schema.json',
    'utf8',
  ),
  [`${root}/Tests/MyHubCoreTests/Fixtures/backup.json`]: await readFile('contracts/v2/fixtures/backup.json', 'utf8'),
  [`${root}/Tests/MyHubCoreTests/Fixtures/expected.json`]: await readFile(
    'contracts/v2/fixtures/expected.json',
    'utf8',
  ),
}
for (const [path, content] of Object.entries(files)) {
  if (process.argv.includes('--check')) {
    if ((await readFile(path, 'utf8')) !== content) throw new Error(`Generated native contract drift: ${path}`)
  } else {
    await mkdir(path.slice(0, path.lastIndexOf('/')), { recursive: true })
    await writeFile(path, content)
  }
}
